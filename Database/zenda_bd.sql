-- =====================================================================
-- 2.1 Funciones de cascada (RN-018)
-- =====================================================================
-- Una única implementación SQL de la cascada evidencia -> carpeta -> fase.
-- La usan tanto el seed/migración como los controladores para evitar cuatro
-- copias divergentes de la misma regla.
CREATE OR REPLACE FUNCTION zenda_recalcular_carpeta(p_carpeta_id int)
RETURNS varchar(20)
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(20);
BEGIN
  SELECT CASE
           WHEN COUNT(ev.evidencia_id) = 0 THEN 'Pendiente'
           WHEN BOOL_OR(ult.resultado = 'REPROBADO') THEN 'Desaprobada'
           WHEN COUNT(*) FILTER (WHERE ult.resultado = 'APROBADO') = COUNT(ev.evidencia_id)
             THEN 'Aprobada'
           ELSE 'En revisión'
         END
    INTO v_estado
  FROM carpetas c
  LEFT JOIN evidencias ev ON ev.carpeta_id = c.carpeta_id
  LEFT JOIN LATERAL (
    SELECT e2.resultado
    FROM evaluaciones e2
    WHERE e2.evidencia_id = ev.evidencia_id
    ORDER BY e2.evaluacion_id DESC
    LIMIT 1
  ) ult ON true
  WHERE c.carpeta_id = p_carpeta_id
  GROUP BY c.carpeta_id;

  v_estado := COALESCE(v_estado, 'Pendiente');

  UPDATE carpetas SET estado_carpeta = v_estado WHERE carpeta_id = p_carpeta_id;

  RETURN v_estado;
END;
$$;

CREATE OR REPLACE FUNCTION zenda_recalcular_fase(p_fase_id int)
RETURNS varchar(20)
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(20);
BEGIN
  SELECT CASE
           WHEN COUNT(ev.evidencia_id) = 0 THEN 'Pendiente'
           WHEN BOOL_OR(ult.resultado = 'REPROBADO') THEN 'Desaprobada'
           WHEN COUNT(*) FILTER (WHERE ult.resultado = 'APROBADO') = COUNT(ev.evidencia_id)
             THEN 'Aprobada'
           ELSE 'En revisión'
         END
    INTO v_estado
  FROM fases f
  LEFT JOIN carpetas c ON c.fase_id = f.fase_id
  LEFT JOIN evidencias ev ON ev.carpeta_id = c.carpeta_id
  LEFT JOIN LATERAL (
    SELECT e2.resultado
    FROM evaluaciones e2
    WHERE e2.evidencia_id = ev.evidencia_id
    ORDER BY e2.evaluacion_id DESC
    LIMIT 1
  ) ult ON true
  WHERE f.fase_id = p_fase_id
  GROUP BY f.fase_id;

  v_estado := COALESCE(v_estado, 'Pendiente');

  UPDATE fases SET estado_fase = v_estado WHERE fase_id = p_fase_id;

  RETURN v_estado;
END;
$$;

