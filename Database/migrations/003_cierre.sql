-- ZENDA — Migración 003: cierre de Semanas 1 y 2
-- =====================================================================
-- Aplica sobre una base creada con zenda_bd.sql o con la migración 002.
-- Es idempotente: puede ejecutarse varias veces sin fallar ni duplicar.
--
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f Database/migrations/003_cierre.sql
--
-- Cambios:
--   1. Verificación de correo (RS-006): columna correo_verificado y tabla
--      verificacion_correo. Los usuarios existentes quedan verificados.
--   2. Sesión segura (HU-004 / H-13): tabla sesiones_refresh para tokens de
--      refresco opacos, con rotación y revocación en el cierre de sesión.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. Verificación de correo
-- ---------------------------------------------------------------------
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "correo_verificado" boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS "verificacion_correo" (
  "verificacion_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL REFERENCES "usuarios" ("usuario_id") ON DELETE CASCADE,
  "token_hash" char(64) UNIQUE NOT NULL,
  "expira_en" timestamp NOT NULL,
  "usado_en" timestamp,
  "creado_en" timestamp NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "idx_verificacion_usuario"
  ON "verificacion_correo" ("usuario_id", "expira_en" DESC);

-- ---------------------------------------------------------------------
-- 2. Sesión segura: tokens de refresco con rotación y revocación
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "sesiones_refresh" (
  "sesion_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL REFERENCES "usuarios" ("usuario_id") ON DELETE CASCADE,
  "token_hash" char(64) UNIQUE NOT NULL,
  "expira_en" timestamp NOT NULL,
  "revocado_en" timestamp,
  "creado_en" timestamp NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "idx_sesiones_refresh_usuario"
  ON "sesiones_refresh" ("usuario_id", "expira_en" DESC);

COMMIT;
