ALTER TABLE "integrantes_grupo" DROP COLUMN IF EXISTS "rol_scrum";

-- ---------------------------------------------------------------------
-- 2. Seguridad de sesiones y aceptaciones legales (C-01, HU-001)
-- ---------------------------------------------------------------------
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "token_version" int NOT NULL DEFAULT 0;
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "acepta_terminos" boolean NOT NULL DEFAULT false;
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "acepta_privacidad" boolean NOT NULL DEFAULT false;
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "acepta_cookies" boolean NOT NULL DEFAULT false;
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "acepta_tratamiento_datos" boolean NOT NULL DEFAULT false;
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "fecha_aceptacion_legal" timestamp;

CREATE TABLE IF NOT EXISTS "recuperacion_contrasena" (
  "recuperacion_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" int NOT NULL REFERENCES "usuarios" ("usuario_id") ON DELETE CASCADE,
