-- 5. Limpieza y normalización de datos antes de los CHECK (C-04, C-07)
-- ---------------------------------------------------------------------
UPDATE "evaluaciones"
SET "resultado" = upper(trim("resultado"))
WHERE "resultado" IS NOT NULL;

UPDATE "evidencias"
SET "tipo_evidencia" = 'Enlace'
WHERE "tipo_evidencia" NOT IN ('Documento', 'Imagen', 'Video', 'Enlace');

-- Las ubicaciones heredadas inválidas NO se reescriben: se conservan para no
-- perder evidencia histórica y la restricción se añade como NOT VALID. Las
-- filas nuevas y las que se actualicen sí quedan validadas.
DO $$
DECLARE
  v_invalidas int;
BEGIN
  SELECT count(*) INTO v_invalidas
  FROM "evidencias"
  WHERE "ubicacion" !~* '^https?://[^[:space:]]+$'
     OR length("ubicacion") > 500;

  IF v_invalidas > 0 THEN
    RAISE NOTICE
      'Migración 002: % evidencia(s) conservan ubicaciones heredadas inválidas; chk_evidencias_ubicacion queda NOT VALID.',
      v_invalidas;
  END IF;
END $$;

-- ---------------------------------------------------------------------
-- 6. Funciones SQL de cascada (RN-018)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION zenda_recalcular_carpeta(p_carpeta_id int)
RETURNS varchar(20)
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(20);
BEGIN
  SELECT CASE
           WHEN COUNT(ev.evidencia_id) = 0 THEN 'Pendiente'
           WHEN BOOL_OR(ult.resultado = 'REPROBADO') THEN 'Desaprobada'
           WHEN COUNT(*) FILTER (WHERE ult.resultado = 'APROBADO') = COUNT(ev.evidencia_id)
             THEN 'Aprobada'
           ELSE 'En revisión'
         END
    INTO v_estado
  FROM carpetas c
  LEFT JOIN evidencias ev ON ev.carpeta_id = c.carpeta_id
  LEFT JOIN LATERAL (
    SELECT e2.resultado
    FROM evaluaciones e2
    WHERE e2.evidencia_id = ev.evidencia_id
    ORDER BY e2.evaluacion_id DESC
    LIMIT 1
  ) ult ON true
  WHERE c.carpeta_id = p_carpeta_id
  GROUP BY c.carpeta_id;

  v_estado := COALESCE(v_estado, 'Pendiente');
  UPDATE carpetas SET estado_carpeta = v_estado WHERE carpeta_id = p_carpeta_id;
  RETURN v_estado;
END;
$$;

CREATE OR REPLACE FUNCTION zenda_recalcular_fase(p_fase_id int)
RETURNS varchar(20)
LANGUAGE plpgsql
AS $$
DECLARE
  v_estado varchar(20);
BEGIN
  SELECT CASE
           WHEN COUNT(ev.evidencia_id) = 0 THEN 'Pendiente'
           WHEN BOOL_OR(ult.resultado = 'REPROBADO') THEN 'Desaprobada'
           WHEN COUNT(*) FILTER (WHERE ult.resultado = 'APROBADO') = COUNT(ev.evidencia_id)
             THEN 'Aprobada'
           ELSE 'En revisión'
         END
    INTO v_estado
  FROM fases f
  LEFT JOIN carpetas c ON c.fase_id = f.fase_id
  LEFT JOIN evidencias ev ON ev.carpeta_id = c.carpeta_id
  LEFT JOIN LATERAL (
    SELECT e2.resultado
    FROM evaluaciones e2
    WHERE e2.evidencia_id = ev.evidencia_id
    ORDER BY e2.evaluacion_id DESC
    LIMIT 1
  ) ult ON true
  WHERE f.fase_id = p_fase_id
  GROUP BY f.fase_id;

  v_estado := COALESCE(v_estado, 'Pendiente');
  UPDATE fases SET estado_fase = v_estado WHERE fase_id = p_fase_id;
  RETURN v_estado;
END;
$$;

-- Recalcular SIEMPRE antes de añadir los CHECK de estado.
SELECT zenda_recalcular_carpeta(carpeta_id) FROM carpetas;
SELECT zenda_recalcular_fase(fase_id) FROM fases;

