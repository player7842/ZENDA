-- ---------------------------------------------------------------------
-- 3. Cupo y grupo General (RN-006, RN-009, C-05, C-06)
-- ---------------------------------------------------------------------
ALTER TABLE "grupos" ADD COLUMN IF NOT EXISTS "cupo_maximo" int;
ALTER TABLE "grupos" ADD COLUMN IF NOT EXISTS "es_general" boolean NOT NULL DEFAULT false;

-- El cupo nunca queda por debajo de los integrantes activos que ya existen.
UPDATE "grupos" g
SET "cupo_maximo" = LEAST(
  50,
  GREATEST(
    COALESCE(g."cupo_maximo", 6),
    1,
    (
      SELECT COUNT(*)::int
      FROM "integrantes_grupo" ig
      WHERE ig."grupo_id" = g."grupo_id"
        AND ig."estado_integrante" = 'Activo'
    )
  )
);

UPDATE "grupos" SET "cupo_maximo" = 6 WHERE "cupo_maximo" IS NULL;
ALTER TABLE "grupos" ALTER COLUMN "cupo_maximo" SET DEFAULT 6;
ALTER TABLE "grupos" ALTER COLUMN "cupo_maximo" SET NOT NULL;

-- Promueve como General solo los grupos llamados "General" que NO tengan
-- proyecto. Un grupo de trabajo legado llamado "General" conserva su nombre,
-- código, integrantes y proyecto: no se convierte en el General de la ficha
-- ni se renombra (C-05).
WITH candidatos AS (
  SELECT g."grupo_id",
         g."ficha_id",
         ROW_NUMBER() OVER (PARTITION BY g."ficha_id" ORDER BY g."grupo_id") AS orden
  FROM "grupos" g
  WHERE lower(g."nombre_grupo") = 'general'
    AND NOT EXISTS (
      SELECT 1 FROM "proyectos" p WHERE p."grupo_id" = g."grupo_id"
    )
)
UPDATE "grupos" g
SET "nombre_grupo" = 'General',
    -- Si otra fila ya usa GEN-<ficha> (por ejemplo, un General legado que
    -- terminó con proyecto), se conserva el código actual para no chocar con
    -- la restricción UNIQUE.
    "codigo_grupo" = CASE
      WHEN g."codigo_grupo" = 'GEN-' || f."numero_ficha" THEN g."codigo_grupo"
      WHEN EXISTS (
        SELECT 1 FROM "grupos" otro
        WHERE otro."codigo_grupo" = 'GEN-' || f."numero_ficha"
      ) THEN g."codigo_grupo"
      ELSE 'GEN-' || f."numero_ficha"
    END,
    "cupo_maximo" = 50,
    "es_general" = true
FROM candidatos c
JOIN "fichas" f ON f."ficha_id" = c."ficha_id"
WHERE g."grupo_id" = c."grupo_id"
  AND c.orden = 1;

CREATE UNIQUE INDEX IF NOT EXISTS "uq_grupo_general_por_ficha"
  ON "grupos" ("ficha_id")
  WHERE "es_general";

-- Crea el General que falte cuando la ficha ya tiene algún integrante o
-- grupo del que tomar un líder. Si la ficha está vacía, el primer registro
-- la creará con el aprendiz como líder (obtenerOCrearGrupoGeneral).
INSERT INTO "grupos"
  ("ficha_id", "lider_id", "nombre_grupo", "codigo_grupo",
   "cupo_maximo", "estado_grupo", "fecha_creacion", "es_general")
SELECT f."ficha_id",
       lider."lider_id",
       'General',
       -- RN-006 usa GEN-<ficha>; si ese código ya lo ocupa un grupo legado
       -- (un General que terminó con proyecto), se añade un sufijo estable.
       CASE
         WHEN NOT EXISTS (
           SELECT 1 FROM "grupos" ocupado
           WHERE ocupado."codigo_grupo" = 'GEN-' || f."numero_ficha"
         ) THEN 'GEN-' || f."numero_ficha"
         WHEN NOT EXISTS (
           SELECT 1 FROM "grupos" ocupado
           WHERE ocupado."codigo_grupo" = 'GEN-' || f."numero_ficha" || '-' || f."ficha_id"
         ) THEN 'GEN-' || f."numero_ficha" || '-' || f."ficha_id"
         ELSE 'GEN-' || f."numero_ficha" || '-' || f."ficha_id" || '-' || (
           SELECT COALESCE(MAX(grupo_id), 0) + 1 FROM "grupos"
         )
       END,
       50,
       'Activo',
       now(),
       true
FROM "fichas" f
JOIN LATERAL (
  SELECT COALESCE(
    (
      SELECT ig."usuario_id"
      FROM "integrantes_grupo" ig
      JOIN "grupos" g ON g."grupo_id" = ig."grupo_id"
      WHERE g."ficha_id" = f."ficha_id"
        AND ig."estado_integrante" = 'Activo'
      ORDER BY ig."integrante_id"
      LIMIT 1
    ),
    (
      SELECT g."lider_id"
      FROM "grupos" g
      WHERE g."ficha_id" = f."ficha_id"
      ORDER BY g."grupo_id"
      LIMIT 1
    )
  ) AS "lider_id"
) lider ON lider."lider_id" IS NOT NULL
WHERE NOT EXISTS (
  SELECT 1 FROM "grupos" g
  WHERE g."ficha_id" = f."ficha_id" AND g."es_general"
)
ON CONFLICT ("ficha_id") WHERE "es_general" DO NOTHING;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'chk_grupos_cupo'
  ) THEN
    ALTER TABLE "grupos"
      ADD CONSTRAINT "chk_grupos_cupo" CHECK ("cupo_maximo" BETWEEN 1 AND 50);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'chk_grupos_general_nombre'
  ) THEN
    -- Un grupo de trabajo legado puede llamarse "General"; solo se exige el
    -- nombre exacto cuando la fila es el General de la ficha.
    ALTER TABLE "grupos"
      ADD CONSTRAINT "chk_grupos_general_nombre" CHECK (
        NOT "es_general" OR "nombre_grupo" = 'General'
      );
  END IF;
END $$;

