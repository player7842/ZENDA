SET "nombre_grupo" = 'Grupo importado ' || g."grupo_id",
    "codigo_grupo" = 'MIG-' || g."grupo_id",
    "es_general" = false
FROM ranking r
WHERE g."grupo_id" = r."grupo_id" AND r.orden > 1;

