-- Es idempotente: puede ejecutarse varias veces sin fallar ni duplicar.
--
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f Database/migrations/002_semana2.sql
--
-- Cambios:
--   1. Sin sub-roles Scrum; el líder es grupos.lider_id.
--   2. Cupo de grupo (RN-009) y grupo General por bandera es_general (C-05).
--   3. Estado de carpeta y funciones SQL de cascada (RN-018).
--   4. Historial de instructor_ficha (H-07, HU-011).
--   5. Tokens de recuperación de un solo uso y versión de sesión (C-01).
--   6. Validaciones de evidencias (C-07), índices y recálculo de estados.
--
-- Orden importante (C-04): primero se crean las columnas y funciones, después
-- se recalculan los estados y solo al final se añaden los CHECK. Así una base
-- antigua con estados incoherentes no rompe la migración.
