WITH ranking AS (
  SELECT "grupo_id",
         "ficha_id",
         ROW_NUMBER() OVER (PARTITION BY "ficha_id" ORDER BY "grupo_id") AS orden
  FROM "grupos"
  WHERE lower("nombre_grupo") = 'general'
)
